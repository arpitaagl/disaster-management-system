-- Ensure the incident persistence table exists on fresh Supabase projects.
-- Safe to run more than once in Supabase SQL Editor.
CREATE TABLE IF NOT EXISTS public.incidents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_code text,
    title text NOT NULL DEFAULT 'Unclassified',
    hazard_type text NOT NULL DEFAULT 'Unclassified',
    location text NOT NULL DEFAULT 'Unknown',
    description text NOT NULL DEFAULT '',
    severity text NOT NULL DEFAULT 'Unknown',
    status text NOT NULL DEFAULT 'Active',
    people_affected integer NOT NULL DEFAULT 0,
    source text NOT NULL DEFAULT 'operator-report',
    incident_data jsonb NOT NULL DEFAULT '{}'::jsonb,
    analysis_data jsonb NOT NULL DEFAULT '{}'::jsonb,
    assignment_data jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

